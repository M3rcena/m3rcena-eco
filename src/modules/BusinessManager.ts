export class BusinessManager {
  private bank: BankManager;
  private catalog: Map<string, BusinessConfig> = new Map();
  private maxAccumulationHours: number;

  constructor(
    bank: BankManager,
    initialCatalog: BusinessConfig[] = DEFAULT_BUSINESS_CATALOG,
    maxAccumulationHours: number = 24
  ) {
    this.bank = bank;
    this.maxAccumulationHours = maxAccumulationHours;
    for (const b of initialCatalog) {
      this.catalog.set(b.id, b);
    }
  }

  /**
   * Returns all available businesses in the catalog.
   */
  public getCatalog(): BusinessConfig[] {
    return Array.from(this.catalog.values());
  }

  /**
   * Retrieves business configuration by ID.
   */
  public getBusinessConfig(id: string): BusinessConfig | undefined {
    return this.catalog.get(id);
  }

  /**
   * Registers a new custom business.
   */
  public registerBusiness(config: BusinessConfig): void {
    this.catalog.set(config.id, config);
  }

  /**
   * Calculates the upgrade cost for a business from its current level.
   */
  public calculateUpgradeCost(business: UserBusiness): number {
    const config = this.catalog.get(business.businessId);
    if (!config) return 0;
    return Math.floor(config.baseCost * Math.pow(config.upgradeCostMultiplier, business.level));
  }

  /**
   * Calculates employee hiring cost for a business.
   */
  public calculateEmployeeHiringCost(business: UserBusiness, count: number): number {
    const config = this.catalog.get(business.businessId);
    if (!config) return 0;
    const basePerEmployee = Math.floor(config.baseCost * 0.15);
    return basePerEmployee * count;
  }

  /**
   * Calculates the hourly revenue generated by a business.
   */
  public calculateHourlyRevenue(business: UserBusiness): number {
    const config = this.catalog.get(business.businessId);
    if (!config) return 0;

    const levelMultiplier = Math.pow(config.revenueMultiplier, business.level - 1);
    const employeeBonus = 1 + business.employees * 0.1; // +10% per employee
    return Math.floor(config.baseHourlyRevenue * levelMultiplier * employeeBonus);
  }

  /**
   * Computes pending unclaimed revenue for a business based on time elapsed.
   */
  public calculatePendingRevenue(business: UserBusiness): number {
    const elapsedMs = Math.max(0, Date.now() - business.lastCollected);
    const maxMs = this.maxAccumulationHours * 60 * 60 * 1000;
    const effectiveElapsedMs = Math.min(elapsedMs, maxMs);

    const hourly = this.calculateHourlyRevenue(business);
    const hours = effectiveElapsedMs / (60 * 60 * 1000);
    return Math.floor(hourly * hours);
  }

  /**
   * Retrieves all businesses owned by a user, enriched with pending revenue and stats.
   */
  public async getUserBusinesses(
    userId: string,
    guildId?: string
  ): Promise<
    Array<{
      business: UserBusiness;
      config: BusinessConfig;
      pendingRevenue: number;
      hourlyRevenue: number;
      upgradeCost: number;
    }>
  > {
    const acc = await this.bank.getAccount(userId, guildId);
    return acc.businesses
      .map((b) => {
        const config = this.catalog.get(b.businessId);
        if (!config) return null;
        return {
          business: b,
          config,
          pendingRevenue: this.calculatePendingRevenue(b),
          hourlyRevenue: this.calculateHourlyRevenue(b),
          upgradeCost: this.calculateUpgradeCost(b),
        };
      })
      .filter((b): b is NonNullable<typeof b> => b !== null);
  }

  /**
   * Purchases a new business enterprise.
   */
  public async buyBusiness(
    userId: string,
    businessId: string,
    guildId?: string
  ): Promise<{
    success: boolean;
    business?: UserBusiness;
    cost: number;
    newWallet: number;
    error?: string;
  }> {
    const config = this.catalog.get(businessId);
    if (!config) {
      return { success: false, cost: 0, newWallet: 0, error: `Business "${businessId}" does not exist in the catalog.` };
    }

    const acc = await this.bank.getAccount(userId, guildId);
    const alreadyOwns = acc.businesses.some((b) => b.businessId === businessId);
    if (alreadyOwns) {
      return {
        success: false,
        cost: 0,
        newWallet: acc.wallet,
        error: `You already own ${config.name}! Upgrade your existing facility instead.`,
      };
    }

    if (acc.wallet < config.baseCost) {
      return {
        success: false,
        cost: config.baseCost,
        newWallet: acc.wallet,
        error: `Insufficient funds! ${config.name} costs ${config.baseCost.toLocaleString()}, but you have ${acc.wallet.toLocaleString()}.`,
      };
    }

    acc.wallet -= config.baseCost;
    acc.stats.totalSpent += config.baseCost;

    const newBusiness: UserBusiness = {
      id: `${businessId}_${Date.now()}`,
      businessId: config.id,
      name: config.name,
      level: 1,
      employees: 0,
      lastCollected: Date.now(),
      totalCollected: 0,
    };

    acc.businesses.push(newBusiness);
    await this.bank.saveAccount(acc);

    return {
      success: true,
      business: newBusiness,
      cost: config.baseCost,
      newWallet: acc.wallet,
    };
  }

  /**
   * Upgrades an existing business level.
   */
  public async upgradeBusiness(
    userId: string,
    businessId: string,
    guildId?: string
  ): Promise<{
    success: boolean;
    business?: UserBusiness;
    newLevel: number;
    upgradeCost: number;
    newWallet: number;
    error?: string;
  }> {
    const acc = await this.bank.getAccount(userId, guildId);
    const bIndex = acc.businesses.findIndex((b) => b.businessId === businessId);
    if (bIndex === -1) {
      return { success: false, newLevel: 0, upgradeCost: 0, newWallet: acc.wallet, error: "You do not own this business." };
    }

    const business = acc.businesses[bIndex];
    const config = this.catalog.get(business.businessId);
    if (!config) {
      return { success: false, newLevel: 0, upgradeCost: 0, newWallet: acc.wallet, error: "Business config not found." };
    }

    if (business.level >= config.maxLevel) {
      return {
        success: false,
        newLevel: business.level,
        upgradeCost: 0,
        newWallet: acc.wallet,
        error: `${business.name} is already at maximum level (${config.maxLevel})!`,
      };
    }

    const cost = this.calculateUpgradeCost(business);
    if (acc.wallet < cost) {
      return {
        success: false,
        newLevel: business.level,
        upgradeCost: cost,
        newWallet: acc.wallet,
        error: `Insufficient funds to upgrade! Cost: ${cost.toLocaleString()}, Wallet: ${acc.wallet.toLocaleString()}.`,
      };
    }

    acc.wallet -= cost;
    acc.stats.totalSpent += cost;
    business.level += 1;

    await this.bank.saveAccount(acc);

    return {
      success: true,
      business,
      newLevel: business.level,
      upgradeCost: cost,
      newWallet: acc.wallet,
    };
  }

  /**
   * Hires additional staff members to boost output.
   */
  public async hireEmployees(
    userId: string,
    businessId: string,
    count: number = 1,
    guildId?: string
  ): Promise<{
    success: boolean;
    business?: UserBusiness;
    totalEmployees: number;
    cost: number;
    newWallet: number;
    error?: string;
  }> {
    if (count <= 0) {
      return { success: false, totalEmployees: 0, cost: 0, newWallet: 0, error: "Count must be greater than zero." };
    }

    const acc = await this.bank.getAccount(userId, guildId);
    const bIndex = acc.businesses.findIndex((b) => b.businessId === businessId);
    if (bIndex === -1) {
      return { success: false, totalEmployees: 0, cost: 0, newWallet: acc.wallet, error: "You do not own this business." };
    }

    const business = acc.businesses[bIndex];
    const maxEmployees = business.level * 5;
    if (business.employees + count > maxEmployees) {
      return {
        success: false,
        totalEmployees: business.employees,
        cost: 0,
        newWallet: acc.wallet,
        error: `At Level ${business.level}, this business can only support up to ${maxEmployees} employees (current: ${business.employees}). Upgrade first!`,
      };
    }

    const cost = this.calculateEmployeeHiringCost(business, count);
    if (acc.wallet < cost) {
      return {
        success: false,
        totalEmployees: business.employees,
        cost,
        newWallet: acc.wallet,
        error: `Insufficient funds! Hiring ${count} employee(s) costs ${cost.toLocaleString()}, Wallet: ${acc.wallet.toLocaleString()}.`,
      };
    }

    acc.wallet -= cost;
    acc.stats.totalSpent += cost;
    business.employees += count;

    await this.bank.saveAccount(acc);

    return {
      success: true,
      business,
      totalEmployees: business.employees,
      cost,
      newWallet: acc.wallet,
    };
  }

  /**
   * Collects accumulated passive profits from all owned businesses or a specific business.
   */
  public async collectRevenue(
    userId: string,
    businessId?: string,
    guildId?: string
  ): Promise<{
    success: boolean;
    collected: number;
    newWallet: number;
    summary: Array<{ businessId: string; name: string; amount: number }>;
    error?: string;
  }> {
    const acc = await this.bank.getAccount(userId, guildId);
    if (acc.businesses.length === 0) {
      return { success: false, collected: 0, newWallet: acc.wallet, summary: [], error: "You do not own any businesses yet." };
    }

    const targets = businessId
      ? acc.businesses.filter((b) => b.businessId === businessId)
      : acc.businesses;

    if (targets.length === 0) {
      return { success: false, collected: 0, newWallet: acc.wallet, summary: [], error: "Selected business not found." };
    }

    let totalCollected = 0;
    const summary: Array<{ businessId: string; name: string; amount: number }> = [];

    for (const b of targets) {
      const revenue = this.calculatePendingRevenue(b);
      if (revenue > 0) {
        totalCollected += revenue;
        b.lastCollected = Date.now();
        b.totalCollected += revenue;
        summary.push({ businessId: b.businessId, name: b.name, amount: revenue });
      }
    }

    if (totalCollected <= 0) {
      return {
        success: false,
        collected: 0,
        newWallet: acc.wallet,
        summary: [],
        error: "No profits have accumulated yet! Check back in a little while.",
      };
    }

    acc.wallet += totalCollected;
    acc.stats.totalEarned += totalCollected;

    await this.bank.saveAccount(acc);

    return {
      success: true,
      collected: totalCollected,
      newWallet: acc.wallet,
      summary,
    };
  }
}
